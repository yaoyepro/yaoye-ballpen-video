"""Stage 3 glue: concatenate engine fragments + the project's scenes.js into <project>/build/mv.js.
Re-run after ANY change to scenes.js, project.json, timeline.json or sprite data (bpmv.py does it automatically)."""
import json, os, hashlib
from common import SKILL_DIR, die

ORDER_BEFORE = ["core.js", "pages.js", "doodles.js", "auto.js"]
ORDER_AFTER = ["main.js", "selfcheck.js"]

def assemble(prj):
    eng = os.path.join(SKILL_DIR, "engine")
    scenes = prj.p(prj.cfg["scenes"])
    if not os.path.exists(scenes):
        die(f"scenes file not found: {scenes} (copy templates/scenes.template.js and edit)")
    if not os.path.exists(prj.timeline_file):
        die("work/timeline.json missing - run: python bpmv.py timeline")
    cfg = prj.engine_cfg()
    parts = ["// AUTO-GENERATED by yaoye-ballpen-video/scripts/assemble.py - do not edit; edit scenes.js / project.json instead\n",
             f"const ENGINE_DIR={json.dumps(eng)};\nconst PROJECT_DIR={json.dumps(prj.dir)};\nconst CFG={json.dumps(cfg, ensure_ascii=False)};\n"]
    for f in ORDER_BEFORE:
        parts.append(f"\n// ===== engine/{f} =====\n" + open(os.path.join(eng, f), encoding="utf-8").read())
    parts.append("\n// ===== project scenes.js =====\n" + open(scenes, encoding="utf-8").read())
    for f in ORDER_AFTER:
        parts.append(f"\n// ===== engine/{f} =====\n" + open(os.path.join(eng, f), encoding="utf-8").read())
    src = "".join(parts)
    # the chunk cache is keyed by everything that influences pixels
    h = hashlib.sha256(src.encode("utf-8"))
    plan = prj.p("work", "plan.json")
    for extra in [prj.timeline_file] + ([plan] if os.path.exists(plan) else []) + sorted(os.path.join(prj.p("data"), f) for f in os.listdir(prj.p("data")) if f.endswith(".json")):
        h.update(open(extra, "rb").read())
    out = prj.p("build", "mv.js")
    with open(out, "w", encoding="utf-8") as f:
        f.write(src)
    with open(prj.p("build", "mv.hash"), "w") as f:
        f.write(h.hexdigest())
    print("assembled", out)
    return out, h.hexdigest()
