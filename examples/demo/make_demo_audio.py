"""make_demo_audio.py - builds the package's DEMO song (instrumental) from code, so it is license-free.

Nothing here is sampled or copied: every sound is a sine/noise formula below (numpy only).
The melody plays one note per lyric syllable (8th notes), so the lyric timeline in timeline.locked.json lines up
with what you hear. Run:  python make_demo_audio.py <preset> <out.mp3>      preset: lullaby | upbeat
License of the output: CC0 / public domain (generated by this script)."""
import json, os, subprocess, sys
import numpy as np

SR = 44100
PRESETS = {
    # bpm, chord loop (root midi + quality), melody per line as (start_bar, [midi notes as 8ths], hold_beats), total bars
    "lullaby": {"bpm": 120, "bars": 8, "kick": False, "offset": 0.5,
                "chords": [(48, "maj"), (43, "maj"), (45, "min"), (41, "maj")],
                "lines": [(0, [64, 67, 69, 67, 64, 62, 60], 3), (2, [62, 64, 67, 69, 67, 64, 62], 3),
                          (4, [64, 67, 72, 71, 69, 67, 64], 3), (6, [65, 64, 62, 64, 62, 60, 60], 4)]},
    "upbeat": {"bpm": 120, "bars": 8, "kick": True,
               "chords": [(45, "min"), (41, "maj"), (48, "maj"), (43, "maj")],
               "lines": [(0.5, [69, 72, 74, 72, 69, 67], 1), (1.5, [67, 69, 72, 74, 76, 74, 72], 1),
                         (2.5, [72, 74, 76, 74, 72, 69, 67], 1), (3.5, [76, 74, 76, 79, 76, 74, 76, 79], 0.5),
                         (4.75, [72, 74, 76, 77, 76, 74, 72, 71, 72, 74], 1), (6.25, [76, 74, 76, 79, 76, 74, 72, 72], 2)]},
}

def mtof(m): return 440.0 * 2 ** ((m - 69) / 12)

def pluck(f, dur, amp=0.25):
    t = np.arange(int(dur * SR)) / SR
    env = np.exp(-t * 3.2) * np.minimum(1, t * 200)
    w = np.sin(2 * np.pi * f * t) + 0.35 * np.sin(4 * np.pi * f * t) + 0.12 * np.sin(6 * np.pi * f * t)
    return amp * env * w

def pad(fs, dur, amp=0.07):
    t = np.arange(int(dur * SR)) / SR
    env = np.minimum(1, t / 0.4) * np.minimum(1, (dur - t) / 0.4).clip(0)
    return amp * env * sum(np.sin(2 * np.pi * f * t + k) for k, f in enumerate(fs))

def kick(amp=0.5):
    t = np.arange(int(0.25 * SR)) / SR
    return amp * np.sin(2 * np.pi * (50 + 90 * np.exp(-t * 30)) * t) * np.exp(-t * 14)

def hat(amp=0.05, seed=0):
    t = np.arange(int(0.06 * SR)) / SR
    return amp * np.random.default_rng(seed).standard_normal(len(t)) * np.exp(-t * 70)

def add(buf, x, at):
    i = int(at * SR); j = min(len(buf), i + len(x)); buf[i:j] += x[: j - i]

def build(name):
    P = PRESETS[name]; beat = 60.0 / P["bpm"]; bar = 4 * beat; total = P["bars"] * bar + 1.0
    L = np.zeros(int(total * SR)); R = np.zeros_like(L)
    for b in range(P["bars"]):
        root, q = P["chords"][b % len(P["chords"])]
        third = 3 if q == "min" else 4
        fs = [mtof(root), mtof(root + 7), mtof(root + 12 + third), mtof(root + 12)]
        p = pad(fs, bar + 0.3); add(L, p, b * bar); add(R, p, b * bar)
        for k in range(8):  # soft arpeggio
            n = [root + 12, root + 12 + third, root + 19, root + 24][k % 4]
            x = pluck(mtof(n), 0.6, 0.06); add(L if k % 2 else R, x, b * bar + k * beat / 2)
        if P["kick"]:
            for k in range(4):
                add(L, kick(), b * bar + k * beat); add(R, kick(), b * bar + k * beat)
                add(L, hat(seed=b * 8 + k), b * bar + k * beat + beat / 2); add(R, hat(seed=b * 8 + k + 99), b * bar + k * beat + beat / 2)
    lines = []
    for (sb, notes, hold) in P["lines"]:
        t0 = sb * bar + P.get("offset", 0.0)
        for k, n in enumerate(notes):
            last = k == len(notes) - 1
            x = pluck(mtof(n), (hold * beat if last else beat / 2) + 0.4, 0.22)
            add(L, x, t0 + k * beat / 2); add(R, x, t0 + k * beat / 2)
        lines.append({"song_start": round(t0, 3), "song_end": round(t0 + (len(notes) - 1) * beat / 2 + hold * beat, 3),
                      "syllables": [round(t0 + k * beat / 2, 3) for k in range(len(notes))]})
    st = np.stack([L, R], 1); st /= max(1e-9, np.abs(st).max()) / 0.5
    beats = [round(k * beat, 3) for k in range(int(P["bars"] * 4))]
    return st, {"preset": name, "bpm": P["bpm"], "duration": round(total, 3), "beats": beats, "lines": lines}

if __name__ == "__main__":
    name, out = sys.argv[1], sys.argv[2]
    st, info = build(name)
    wav = out.rsplit(".", 1)[0] + ".tmp.wav"
    import soundfile as sf; sf.write(wav, st, SR)
    subprocess.run(["ffmpeg", "-v", "error", "-y", "-i", wav, "-af", "loudnorm=I=-16:TP=-1.5:LRA=11", "-ar", "44100",
                    "-map_metadata", "-1", "-fflags", "+bitexact", "-c:a", "libmp3lame", "-b:a", "128k", out], check=True)
    os.remove(wav)
    print(json.dumps(info))
